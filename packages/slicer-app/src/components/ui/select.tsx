function SelectContent({
  className,
  children,
  side = "bottom",
  sideOffset = 4,
  align = "center",
  alignOffset = 0,
  // `alignItemWithTrigger` (the "native select" mode) is broken in Base UI
  // 1.7.0 for short lists: SelectPopup's align effect sets
  // `isTopPositioned` whenever the list doesn't overflow
  // (`scrollTop=0 >= maxScrollTop-2` with `maxScrollTop=0`), and that branch
  // collapses the positioner height to the list's natural height and pins
  // its top at the trigger's top — the popup ends up a short strip COVERING
  // the trigger ("shifted up"), with the viewport space below it empty
  // ("wastes the bottom space"). Long lists take the bottom-anchored branch
  // and fill correctly, which is why only short enums (e.g.
  // sparse_infill_pattern in the mock) showed it. Default off → the
  // standard anchored dropdown (same as the preset Comboboxes): hangs
  // 4px below the trigger and tracks it on container scroll.
  alignItemWithTrigger = false,
  ...props
}: SelectPrimitive.Popup.Props &
  Pick<
    SelectPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset" | "alignItemWithTrigger"
  >) {
  return (
    <SelectPrimitive.Portal>
      <SelectPrimitive.Positioner
        // The settings sidebar is its own scrolling container. Fixed
        // positioning keeps the portal anchored to the trigger's viewport
        // rect while that container scrolls; absolute positioning can retain
        // the pre-scroll document rect and jump to the viewport edge.
        positionMethod="fixed"
        sticky
        collisionAvoidance={{ side: "none", align: "shift", fallbackAxisSide: "none" }}
        side={side}
        sideOffset={sideOffset}
        align={align}
        alignOffset={alignOffset}
        alignItemWithTrigger={alignItemWithTrigger}
        className="isolate z-50"
      >
        <SelectPrimitive.Popup
          data-slot="select-content"
          data-align-trigger={alignItemWithTrigger}
          className={cn(
            // transition-none replaces `duration-100`: the positioner
            // rewrites --available-height/--transform-origin, and
            // transition-property: all makes those writes spawn transitions
            // that never advance — Base UI waits on getAnimations().finished
            // to unmount the popup on close, so it would stay mounted forever
            // (same fix as combobox.tsx, 2026-08-16).
            "relative isolate z-50 max-h-(--available-height) w-(--anchor-width) min-w-32 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-lg bg-card text-card-foreground shadow-md ring-1 ring-foreground/10 transition-none data-[align-trigger=true]:animate-none data-[side=bottom]:slide-in-from-top-2 data-[side=inline-end]:slide-in-from-left-2 data-[side=inline-start]:slide-in-from-right-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95",
            className
          )}
          {...props}
        >
          <SelectScrollUpButton />
          <SelectPrimitive.List>{children}</SelectPrimitive.List>
          <SelectScrollDownButton />
        </SelectPrimitive.Popup>
      </SelectPrimitive.Positioner>
    </SelectPrimitive.Portal>
  )
}

