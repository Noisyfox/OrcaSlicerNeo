import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync, renameSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const versionModule = 'packages/slicer-wasm/src/client/version.ts';
const numeric = '(0|[1-9][0-9]*)';
const semver = new RegExp(`^${numeric}\\.${numeric}\\.${numeric}(?:-([0-9A-Za-z-]+(?:\\.[0-9A-Za-z-]+)*))?(?:\\+([0-9A-Za-z-]+(?:\\.[0-9A-Za-z-]+)*))?$`);

export function validateVersion(version) {
  const match = typeof version === 'string' && semver.exec(version);
  if (!match || match[4]?.split('.').some(part => /^0[0-9]+$/.test(part))) {
    throw new Error(`Invalid Neo SemVer: ${String(version)}`);
  }
  return version;
}

export function readNeoVersion(root = repositoryRoot) {
  return validateVersion(JSON.parse(readFileSync(join(root, 'version.json'), 'utf8')).version);
}

function readCoreRevision(root) {
  const entry = execFileSync('git', ['ls-files', '--stage', '--', 'packages/slicer-wasm/cpp'], { cwd: root, encoding: 'utf8' });
  const match = /^160000 ([0-9a-f]{40}) 0\tpackages\/slicer-wasm\/cpp\r?\n?$/.exec(entry);
  if (!match) throw new Error('Cannot resolve the pinned slicing core revision');
  return match[1];
}

export function readBuildInfo(root = repositoryRoot) {
  return { neoVersion: readNeoVersion(root), coreRevision: readCoreRevision(root) };
}

export function readPinnedOrcaVersion(root = repositoryRoot) {
  const revision = readCoreRevision(root);
  const source = execFileSync('git', ['-C', join(root, 'packages/slicer-wasm/cpp'), 'show', `${revision}:version.inc`], { encoding: 'utf8' });
  const match = /^\s*set\(\s*SoftFever_VERSION\s+"([^"]+)"\s*\)/m.exec(source);
  if (!match) throw new Error(`Cannot read OrcaSlicer version from core ${revision}`);
  return match[1];
}

function versionFiles(root, version) {
  const paths = ['package.json'];
  for (const directory of ['apps', 'packages']) {
    for (const entry of readdirSync(join(root, directory), { withFileTypes: true })) {
      if (entry.isDirectory()) paths.push(`${directory}/${entry.name}/package.json`);
    }
  }
  const files = paths.sort().map(path => {
    const text = readFileSync(join(root, path), 'utf8');
    const manifest = JSON.parse(text);
    if (typeof manifest.version !== 'string') throw new Error(`Missing version in ${path}`);
    const content = text.replace(/("version"\s*:\s*")[^"]*(")/, `$1${version}$2`);
    return { path, content };
  });
  const orcaVersion = readPinnedOrcaVersion(root);
  files.push({ path: versionModule, content: `// Generated by scripts/version.mjs from version.json and the pinned core.\nexport const NEO_VERSION = '${version}';\nexport const ORCA_VERSION = ${JSON.stringify(orcaVersion)};\n` });
  return files;
}

export function manageVersions(command, version, root = repositoryRoot) {
  const target = command === 'set' ? validateVersion(version) : readNeoVersion(root);
  const files = versionFiles(root, target);
  if (command === 'check') {
    const mismatches = files.filter(file => readFileSync(join(root, file.path), 'utf8').replaceAll('\r\n', '\n') !== file.content.replaceAll('\r\n', '\n'));
    if (mismatches.length) throw new Error(`Neo version drift in ${mismatches.map(file => file.path).join(', ')}. Run pnpm version:sync.`);
    return target;
  }
  if (!['set', 'sync'].includes(command)) throw new Error(`Unknown version command: ${command}`);
  files.push({ path: 'version.json', content: `${JSON.stringify({ version: target }, null, 2)}\n` });
  for (const { path, content } of files) {
    const destination = join(root, path);
    writeFileSync(`${destination}.version-tmp`, content);
    renameSync(`${destination}.version-tmp`, destination);
  }
  return target;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const [command = 'check', version] = process.argv.slice(2);
    if (command === 'info') console.log(JSON.stringify(readBuildInfo()));
    else if (command === 'core') console.log(readBuildInfo().coreRevision);
    else if (command === 'version') console.log(readNeoVersion());
    else console.log(`Neo ${manageVersions(command, version)}`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
