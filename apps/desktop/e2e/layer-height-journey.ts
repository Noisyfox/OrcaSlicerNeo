import { verifyLayerHeightReplay } from './layer-height-replay';
import { expect as baseExpect, test, type Page } from '@playwright/test';
import { ready } from './arrangement-journey';
import { addPrimitive } from './add-primitive';

const expect = baseExpect.configure({ timeout: 30_000 });

export async function verifyLayerHeight(page: Page) {
  page.on('pageerror', error => console.error('Prepare renderer:', error.message));
  await ready(page);
  await page.getByTestId('config-mode-scoped').click();
  const tool = page.getByTestId('gizmo-btn-layer-height');
  await expect(tool).toBeDisabled();
  await addPrimitive(page, 'Sphere');
  await page.getByTestId('object-list').getByTestId(/^object-\d+$/).first().getByRole('button').first().click();
  await tool.click();
  const panel = page.getByRole('region', { name: 'Variable layer height' });
  const bar = page.getByTestId('layer-height-bar');
  await expect(bar).toBeVisible();
  await expect(panel.getByRole('button', { name: 'Reset' })).toBeDisabled();
  const viewport = page.viewportSize()!;
  await page.setViewportSize({ width: 1024, height: 560 });
  const card = page.getByTestId('gizmo-options');
  await expect(panel.getByRole('heading')).toHaveCSS('font-size', '11px');
  await expect.poll(() => card.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await panel.getByRole('button', { name: 'Smooth', exact: true }).scrollIntoViewIfNeeded();
  await expect(panel.getByRole('button', { name: 'Smooth', exact: true })).toBeInViewport();
  await test.info().attach('compact-layer-height-card', { body: await card.screenshot(), contentType: 'image/png' });
  await page.setViewportSize(viewport);
  const quality = panel.getByRole('slider', { name: 'Quality / Speed' });
  const radius = panel.getByRole('slider', { name: 'Smoothing radius' });
  const keepMin = panel.getByRole('checkbox', { name: 'Keep min' });
  await quality.focus();
  await quality.press('ArrowRight');
  await expect(quality).toHaveValue('0.51');
  await quality.press('ArrowLeft');
  await radius.focus();
  await radius.press('ArrowRight');
  await expect(radius).toHaveValue('6');
  await radius.press('ArrowLeft');
  await keepMin.focus();
  await keepMin.press('Space');
  await expect(keepMin).toBeChecked();
  await keepMin.press('Space');
  await expect(keepMin).not.toBeChecked();
  const box = await bar.boundingBox();
  if (!box) throw new Error('Missing layer height bar');
  const pixel = () => bar.evaluate(el => (el as HTMLCanvasElement).toDataURL());
  const x = box.x + box.width / 2, y = box.y + box.height / 2;
  await page.mouse.move(x, y);
  const initial = await pixel();
  await page.mouse.down();
  await expect.poll(pixel).not.toBe(initial);
  await page.keyboard.press('m');
  await expect(tool).toHaveAttribute('aria-pressed', 'true');
  const first = await pixel();
  await expect.poll(pixel).not.toBe(first);
  await page.mouse.move(x - box.width * 2, y - 15);
  await page.mouse.up();
  const reset = panel.getByRole('button', { name: 'Reset' });
  await expect(reset).toBeEnabled();
  await reset.click();
  await expect(reset).toBeDisabled();
  await expect(panel.getByRole('button', { name: 'Adaptive' })).toBeEnabled();
  await verifyLayerHeightReplay(page, bar, reset);
  await panel.getByRole('button', { name: 'Adaptive' }).click();
  await expect(reset).toBeEnabled();
  await panel.getByRole('button', { name: 'Smooth', exact: true }).click();
  await expect(panel.getByRole('button', { name: 'Done' })).toBeEnabled();
  await panel.getByRole('button', { name: 'Done' }).click();
  await expect(bar).toHaveCount(0);
  await tool.click();
  await expect(reset).toBeEnabled();
  await page.locator('#app-tab-preview').click();
  await expect(bar).toHaveCount(0);
  await page.locator('#app-tab-prepare').click();
  await expect(bar).toBeVisible();
  await panel.getByRole('button', { name: 'Done' }).click();
  const lifecycle = () => page.evaluate(() => (window as unknown as {
    __orcaE2e: { historyRestoreLifecycle(): { phase: string; revision: number; error: string | null } };
  }).__orcaE2e.historyRestoreLifecycle());
  const previous = await lifecycle();
  await page.getByTestId('history-undo').click();
  await expect.poll(lifecycle).toMatchObject({ phase: 'idle', revision: previous.revision + 1, error: null });
  await expect(bar).toBeVisible();
  await page.getByTestId('history-redo').click();
  await expect.poll(lifecycle).toMatchObject({ phase: 'idle', revision: previous.revision + 2, error: null });
  await expect(reset).toBeEnabled();
  await panel.getByRole('button', { name: 'Done' }).click();
  await page.getByTestId('config-mode-project').click();
  await page.getByTestId('config-page-Quality').click();
  await expect(page.locator('[data-testid="configuration-option-lock"]:not([disabled])')).toBeVisible();
  const sublayer = page.getByTestId('config-input-enable_mixed_color_sublayer');
  await expect(sublayer).toHaveAttribute('aria-checked', 'false');
  await sublayer.click();
  const warning = page.getByRole('dialog', { name: 'Variable layer height' });
  await expect(warning).toContainText('poor color mixing quality');
  await warning.getByRole('button', { name: 'OK', exact: true }).click();
  await expect(warning).toHaveCount(0);
  await expect(page.locator('[data-testid="configuration-option-lock"]:not([disabled])')).toBeVisible();
  await expect(sublayer).toHaveAttribute('aria-checked', 'true');
  await expect(tool).toHaveAttribute('aria-pressed', 'false');
  await tool.click();
  await expect(warning).toBeVisible();
  await expect(warning).toHaveCSS('opacity', '1');
  await test.info().attach('mixed-layer-height-warning', { body: await warning.screenshot({ animations: 'disabled' }), contentType: 'image/png' });
  await warning.getByRole('checkbox', { name: 'Do not show again' }).check();
  await warning.getByRole('button', { name: 'OK', exact: true }).click();
  await panel.getByRole('button', { name: 'Done' }).click();
  await tool.click();
  await expect(reset).toBeEnabled();
  await expect(warning).toHaveCount(0);
}
