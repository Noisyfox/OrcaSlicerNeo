import { expect, test, type Page } from '@playwright/test';
import { ready, selectPrinter } from './arrangement-journey';
import { addPrimitive } from './add-primitive';

export async function verifyHeightRanges(page: Page) {
  await ready(page);
  await selectPrinter(page, 'Bambu Lab X1 Carbon 0.4 nozzle');
  await page.getByTestId('config-mode-scoped').click();
  await addPrimitive(page, 'Cube');
  const list = page.getByTestId('object-list');
  const objects = list.getByTestId(/^object-\d+$/);
  const owner = objects.first().getByRole('button').first();
  await owner.click();
  const settings = page.getByTestId('scoped-configuration-panel');
  const tabs = settings.getByRole('tablist', { name: 'Settings category' });
  await tabs.getByRole('tab', { name: 'Strength' }).click();
  const walls = settings.getByTestId('config-input-wall_loops');
  await expect(walls).toBeEnabled();
  const ownerWalls = await walls.inputValue();
  const rowMetrics = () => walls.evaluate(input => {
    const label = input.closest('[data-testid^="config-field-"]')!.querySelector('label')!;
    return [input.clientHeight, getComputedStyle(input).fontSize, getComputedStyle(label).fontSize,
      input.getBoundingClientRect().left > label.getBoundingClientRect().left];
  });
  const objectMetrics = await rowMetrics();
  await settings.screenshot({ path: test.info().outputPath('object-strength.png') });
  await owner.click({ button: 'right' });
  await page.getByTestId('objectlist-height-ranges').click();
  const panel = page.getByRole('region', { name: 'Height range settings' });
  await expect(panel).toBeVisible();
  const first = list.getByRole('button', { name: 'Range 0.00-2.00 (mm)', exact: true });
  const planes = () => page.evaluate(() => (window as unknown as { __orcaE2e: {
    heightRangePlanes: () => Array<{ z: number; opacity: number }>;
  } }).__orcaE2e.heightRangePlanes());
  const layers = list.getByRole('button', { name: 'Layers', exact: true });
  const bounds = panel.getByRole('group', { name: 'Height ranges', exact: true });
  const interval = (min: number, max: number) => bounds.getByRole('group', { name: `Range ${min} to ${max} mm`, exact: true });
  await expect.poll(planes).toEqual([]);
  await expect(tabs).toHaveCount(0);
  await expect(layers).toHaveAttribute('aria-pressed', 'true');
  await list.getByRole('button', { name: 'Collapse Layers' }).click();
  await expect(first).toHaveCount(0);
  await list.getByRole('button', { name: 'Expand Layers' }).click();
  // Clicking Add directly from a dirty endpoint acts after its new bound.
  const initial = interval(0, 2);
  await initial.getByRole('textbox', { name: 'End (mm)' }).fill('3,5');
  await expect.poll(async () => (await planes()).map(p => Math.round(p.z))).toEqual([0, 2]);
  await initial.getByRole('button', { name: 'Add height range' }).click();
  const added = interval(3.5, 5.5);
  await expect(added).toBeVisible();
  await expect(layers).toHaveAttribute('aria-pressed', 'true');
  await added.getByRole('textbox', { name: 'Start (mm)' }).focus();
  await expect.poll(async () => (await planes()).map(p => p.z)).toEqual([3.5, 5.5]);
  await expect.poll(async () => { const p = await planes(); return p[0].opacity > p[1].opacity; }).toBe(true);
  await settings.screenshot({ path: test.info().outputPath('layers-list.png') });
  await added.getByRole('button', { name: 'Remove height range' }).click();
  await expect(added).toHaveCount(0);
  const groupEnd = interval(0, 3.5).getByRole('textbox', { name: 'End (mm)' });
  await groupEnd.fill('-1');
  await groupEnd.press('Enter');
  await expect(groupEnd).toHaveValue('3.5');
  const groupStart = interval(0, 3.5).getByRole('textbox', { name: 'Start (mm)' });
  await groupStart.fill('0.5');
  await groupStart.press('Tab');
  await expect(interval(0.5, 3.5).getByRole('textbox', { name: 'End (mm)' })).toBeFocused();
  await expect.poll(async () => (await planes()).map(p => p.z)).toEqual([0.5, 3.5]);
  const movedStart = interval(0.5, 3.5).getByRole('textbox', { name: 'Start (mm)' });
  await movedStart.fill('0');
  await movedStart.press('Enter');
  await groupEnd.fill('2');
  await groupEnd.press('Enter');
  await expect(interval(0, 2)).toBeVisible();
  await first.click();
  await expect(bounds.getByRole('button')).toHaveCount(0);
  await expect(bounds.getByRole('textbox')).toHaveCount(2);
  await expect(tabs.getByRole('tab', { name: 'Strength' })).toHaveAttribute('aria-selected', 'true');
  await expect(walls).toHaveValue(ownerWalls);
  expect(await rowMetrics()).toEqual(objectMetrics);
  await settings.screenshot({ path: test.info().outputPath('range-strength.png') });
  const wallGroup = panel.getByTestId('config-category-toggle-Walls');
  await wallGroup.click();
  await expect(walls).toBeHidden();
  await wallGroup.click();
  await walls.fill('7');
  await walls.press('Enter');
  await expect(panel.getByTestId('config-reset-wall_loops')).toBeVisible();
  await panel.getByRole('button', { name: 'Search settings' }).click();
  const search = panel.getByTestId('scoped-config-search');
  await search.fill('wall_loops');
  await expect(walls).toHaveCount(1);
  await panel.getByTestId('config-category-toggle-Strength / Walls').click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Reset Walls' }).click();
  await expect(walls).toHaveValue(ownerWalls);
  await panel.getByRole('button', { name: 'Search settings' }).click();
  await tabs.getByRole('tab', { name: 'Frequent' }).click();
  const height = panel.getByTestId('config-input-layer_height');
  const originalHeight = await height.inputValue();
  await expect(panel.getByRole('textbox', { name: 'End (mm)' })).toHaveValue('2');
  await expect.poll(async () => (await planes()).map(p => Math.round(p.z * 1000) / 1000)).toEqual([0, 2]);
  for (const [i, label] of ['Start (mm)', 'End (mm)'].entries()) {
    await panel.getByRole('textbox', { name: label }).focus();
    await expect.poll(async () => { const p = await planes(); return p[i].opacity > p[1 - i].opacity; }).toBe(true);
  }
  const end = panel.getByRole('textbox', { name: 'End (mm)' });
  await end.fill('3');
  await end.press('Enter');
  await expect(list.getByRole('button', { name: 'Range 0.00-3.00 (mm)', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await end.fill('2');
  await end.press('Enter');
  await expect(first).toHaveAttribute('aria-pressed', 'true');
  await layers.click();
  await interval(0, 2).getByRole('button', { name: 'Add height range' }).click();
  const second = list.getByRole('button', { name: 'Range 2.00-4.00 (mm)', exact: true });
  await second.click();
  await expect(second).toHaveAttribute('aria-pressed', 'true');
  await height.fill('0.12');
  await height.press('Enter');
  await expect(height).toHaveValue('0.12');
  await first.click({ modifiers: ['ControlOrMeta'] });
  await expect(height).toHaveAttribute('placeholder', 'Mixed');
  await expect.poll(planes).toEqual([]);
  await expect(panel.getByRole('textbox', { name: 'End (mm)' })).toHaveCount(0);
  await height.fill('0.16');
  await height.press('Enter');
  await expect(height).toHaveValue('0.16');
  await second.click();
  await expect(height).toHaveValue('0.16');
  await first.click();
  await expect(height).toHaveValue('0.16');
  await page.getByTestId('history-undo').click();
  await second.click();
  await expect(height).toHaveValue('0.12');
  await first.click();
  await expect(height).toHaveValue(originalHeight);
  await page.getByTestId('history-redo').click();
  await second.click();
  await expect(height).toHaveValue('0.16');
  await layers.click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Copy ranges' }).click();
  await addPrimitive(page, 'Cube');
  await objects.last().getByRole('button').first().click({ button: 'right' });
  await page.getByTestId('objectlist-paste-ranges').click();
  await objects.last().getByRole('button', { name: 'Range 2.00-4.00 (mm)', exact: true }).click();
  const rack = page.getByTestId('filament-rack');
  await rack.getByTestId('filament-add').click();
  await expect(rack.getByTestId('filament-slot-2')).toBeVisible();
  await rack.getByRole('tab', { name: 'Mixes (0)' }).click();
  await rack.getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Save mix' }).click();
  const base = panel.getByTestId('config-input-extruder');
  await objects.last().getByRole('combobox', { name: 'Range 2.00-4.00 (mm) filament' }).click();
  await page.getByRole('listbox').getByRole('option', { name: /^2 - / }).click();
  await expect(base).toContainText(/^2 - /);
  await tabs.getByRole('tab', { name: 'Multi.' }).click();
  const outer = panel.getByTestId('config-input-outer_wall_filament_id');
  await outer.click();
  // The tree swatch's popup may still be exiting. Use this trigger's listbox.
  await expect(outer).toHaveAttribute('aria-expanded', 'true');
  const outerListId = await outer.getAttribute('aria-controls');
  await page.locator(`[id="${outerListId}"]`).getByRole('option', { name: /^3 - / }).click();
  await expect(outer).toContainText(/^3 - /);
  await rack.getByRole('tab', { name: /Material/ }).click();
  await rack.getByTestId('filament-add').click();
  await expect(outer).toContainText(/^4 - /);
  await panel.getByTestId('config-reset-all').click();
  await expect(outer.locator('[data-slot="select-value"]')).toHaveText('Default');
  await expect(base.locator('[data-slot="select-value"]')).toHaveText('Default');
  await expect(panel.getByTestId('config-reset-all')).toBeDisabled();
  await page.getByTestId('history-undo').click();
  await objects.last().getByRole('button', { name: 'Range 2.00-4.00 (mm)', exact: true }).click();
  await expect(outer).toContainText(/^4 - /);
  await expect(base).toContainText(/^2 - /);
  await owner.click();
  await tabs.getByRole('tab', { name: 'Strength' }).click();
  await expect(walls).toHaveValue(ownerWalls);
  await objects.first().getByRole('button', { name: 'Layers', exact: true }).click();
  await interval(0, 2).getByRole('textbox', { name: 'End (mm)' }).fill('1.5');
  const ownerSecond = objects.first().getByRole('button', { name: 'Range 2.00-4.00 (mm)', exact: true });
  await ownerSecond.click();
  await expect(objects.first().getByRole('button', { name: 'Range 0.00-1.50 (mm)' })).toBeVisible();
  await expect(ownerSecond).toHaveAttribute('aria-pressed', 'true');
  await objects.first().getByRole('button', { name: 'Layers', exact: true }).click();
  await interval(2, 4).getByRole('button', { name: 'Remove height range' }).click();
  await interval(0, 1.5).getByRole('button', { name: 'Remove height range' }).click();
  await expect(objects.first().getByRole('button', { name: 'Layers', exact: true })).toHaveCount(0);
  await expect(owner).toHaveAttribute('data-state', 'selected');
}
