import { _electron } from './electron-fixture';
import { installSliceReceiptObserver, readSliceReceipts } from './runtime-receipts';
import { expect, test } from '@playwright/test';
import { resolve } from 'node:path';
import { selectFixturePrinter } from './printer-selection';

test('flushing editor uses the Material toolbar, keeps Cancel local and stores raw volumes once', async () => {
  const env = { ...process.env, ORCA_E2E: '1' } as Record<string, string>;
  delete env.ELECTRON_RUN_AS_NODE;
  const app = await _electron.launch({ args: ['.'], cwd: resolve(__dirname, '..'), env });
  try {
    const page = await app.firstWindow();
    await expect(page.getByTestId('slicer-status')).toHaveText('Ready', { timeout: 60_000 });
    await page.locator('#app-tab-prepare').click();
    await expect(page.getByTestId('filament-slot-1')).toBeVisible();
    await expect(page.getByTestId('flushing-volumes-open')).toHaveCount(0);
    await installSliceReceiptObserver(page, ['setFlushingVolumes', 'getFlushingVolumes']);
    await page.getByTestId('filament-add').click();
    await expect(page.getByTestId('filament-slot-2')).toBeVisible();
    const button = page.getByTestId('flushing-volumes-open');
    const buttonBox = await button.boundingBox(), addBox = await page.getByTestId('filament-add').boundingBox();
    expect(buttonBox!.x).toBeLessThan(addBox!.x);
    expect(Math.abs(buttonBox!.y - addBox!.y)).toBeLessThan(8);
    await button.click();
    const dialog = page.getByTestId('flushing-volumes-dialog');
    await expect(dialog).toBeVisible();
    const cell = dialog.getByRole('spinbutton', { name: 'From material 1 to material 2' });
    await expect(cell).toBeVisible();
    await expect(dialog.getByRole('spinbutton', { name: 'From material 1 to material 1' })).toHaveAttribute('readonly', '');
    await cell.fill('999'); await cell.blur();
    await dialog.getByTestId('flushing-recalculate').click();
    await expect(cell).not.toHaveValue('999');
    await cell.fill('');
    await expect(dialog.getByTestId('flushing-save')).toBeDisabled();
    await dialog.getByTestId('flushing-recalculate').click();
    await expect(cell).not.toHaveValue('');
    await expect(dialog.getByTestId('flushing-save')).toBeEnabled();
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(dialog).toBeHidden();
    expect((await readSliceReceipts(page) as any[]).filter(r => r.op === 'setFlushingVolumes')).toHaveLength(0);
    await button.click();
    await dialog.locator('#flush-multiplier').fill('1'); await dialog.locator('#flush-multiplier').blur();
    await cell.fill('123'); await cell.blur();
    await dialog.locator('#flush-multiplier').fill('0.5'); await dialog.locator('#flush-multiplier').blur();
    await expect(cell).toHaveValue('62');
    await cell.focus(); await cell.blur();
    await dialog.getByTestId('flushing-save').click(); await expect(dialog).toBeHidden();
    const responses = (await readSliceReceipts(page) as any[]).filter(r => r.direction === 'response' && r.op === 'setFlushingVolumes');
    expect(responses).toHaveLength(1);
    expect(responses[0].result.ok).toBe(true);
    expect(responses[0].result.result.snapshot.flushing.matrix[1]).toBe(123);
    expect(responses[0].result.result.mutation.historyEntryDelta).toBe(1);
    await expect(button).toHaveAttribute('data-modified', 'true');
    await button.click(); await expect(cell).toHaveValue('62');
    await page.screenshot({ path: resolve(__dirname, '../test-results/flushing-dialog.png'), animations: 'disabled' });
    await dialog.getByTestId('flushing-save').click(); await expect(dialog).toBeHidden();
    const noOp = (await readSliceReceipts(page) as any[]).filter(r => r.direction === 'response' && r.op === 'setFlushingVolumes').at(-1);
    expect(noOp.result.result.mutation.historyEntryDelta).toBe(0);
    await button.click();
    await dialog.locator('#flush-multiplier').fill('0'); await dialog.locator('#flush-multiplier').blur();
    await expect(cell).toHaveValue('0'); await expect(cell).toBeDisabled();
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.screenshot({ path: resolve(__dirname, '../test-results/flushing-toolbar.png') });
    if (await page.getByTestId('titlebar-menu-trigger').getAttribute('aria-expanded') !== 'true')
      await page.getByTestId('titlebar-menu-trigger').click();
    await page.getByTestId('menu-file-trigger').focus();
    await page.getByTestId('menu-file-trigger').press('ArrowRight');
    await page.getByTestId('file-preferences').click();
    const preferences = page.getByTestId('project-preferences-dialog');
    await expect(preferences).toBeVisible();
    await preferences.getByRole('combobox', { name: 'Auto flush after changing' }).click();
    await page.getByRole('option', { name: 'None', exact: true }).click();
    await preferences.getByTestId('project-preferences-save').click(); await expect(preferences).toBeHidden();
    if (await page.getByTestId('titlebar-menu-trigger').getAttribute('aria-expanded') !== 'true')
      await page.getByTestId('titlebar-menu-trigger').click();
    await page.getByTestId('menu-file-trigger').focus();
    await page.getByTestId('menu-file-trigger').press('ArrowRight');
    await page.getByTestId('file-preferences').click();
    await expect(preferences.getByRole('combobox', { name: 'Auto flush after changing' })).toContainText('None');
    await preferences.getByTestId('project-preferences-cancel').click();
    if (process.env.ORCA_E2E_REAL === '1') {
      await selectFixturePrinter(page, 'Snapmaker U1 0.4 nozzle');
      await expect(page.getByTestId('filament-slot-4')).toBeVisible();
      await expect(button).toHaveCount(0);
      await selectFixturePrinter(page, 'Bambu Lab H2D 0.4 nozzle');
      await page.getByTestId('filament-add').click();
      await expect(button).toBeVisible();
    }
  } finally { await app.close(); }
});
