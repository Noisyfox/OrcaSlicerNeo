import { expect, type Page } from '@playwright/test';

import { addPrimitive } from './add-primitive';

async function verifyMergeChoices(page: Page, source: number, destination: number, label: string | RegExp) {
  await page.getByTestId(`filament-merge-${source}`).hover();
  const choice = page.getByTestId(`filament-merge-${source}-to-${destination}`);
  await expect(choice).toHaveText(label);
  await expect(choice.locator('span[aria-hidden="true"]')).toHaveCSS('width', '14px');
  await expect(page.getByTestId(`filament-merge-${source}-to-${source}`)).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.keyboard.press('Escape');
}

export async function verifyMixedFilamentEditor(page: Page) {
  await expect(page.getByTestId('slicer-status')).toHaveText('Ready', { timeout: 120000 });
  await page.locator('#app-tab-prepare').click();
  const rack = page.getByTestId('filament-rack');
  const mixes = rack.getByRole('tab', { name: /^Mixes \(\d+\)$/ });
  const material = rack.getByRole('tab', { name: /Material/ });
  await material.focus();
  await material.press('ArrowRight');
  await expect(mixes).toBeFocused();
  await expect(mixes).toHaveAttribute('aria-selected', 'true');
  await expect(mixes).toHaveCSS('font-size', '11px');
  await expect(rack.locator('[data-slot="tabs"]')).toHaveCSS('flex-direction', 'column');
  await expect(rack.getByRole('tabpanel', { name: 'Mixes (0)' })).toBeVisible();
  await expect(rack.getByRole('button', { name: 'Create', exact: true })).toBeDisabled();
  await material.click();
  await rack.getByTestId('filament-add').click();
  await expect(rack.getByTestId('filament-slot-2')).toBeVisible();
  const materialSlot = rack.getByTestId('filament-slot-1');
  const materialSlotHeight = await materialSlot.evaluate(element => getComputedStyle(element).height);
  const materialNumberWidth = await rack.getByTestId('filament-colour-1').evaluate(element => getComputedStyle(element).width);
  await mixes.click();
  await rack.getByRole('button', { name: 'Create', exact: true }).click();
  const editor = page.getByRole('dialog');
  const componentCount = editor.getByRole('combobox', { name: 'Components', exact: true });
  await expect(componentCount).toHaveCSS('height', '24px');
  await expect(componentCount).toHaveCSS('font-size', '13px');
  await expect(editor.getByLabel('Percentage 1')).toHaveValue('50');
  const ratio = editor.getByRole('slider', { name: 'Mix ratio' });
  await ratio.press('ArrowRight');
  await expect(editor.getByLabel('Percentage 1')).toHaveValue('51');
  await editor.getByRole('checkbox', { name: 'Z gradient' }).check();
  await editor.getByRole('button', { name: 'Add point' }).click();
  await editor.getByRole('checkbox', { name: 'Per-part gradient' }).check();
  const viewport = page.viewportSize();
  if (viewport) {
    await page.setViewportSize({ width: viewport.width, height: 400 });
    const body = editor.locator(':scope > .overflow-y-auto');
    await expect.poll(() => body.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true);
    await expect(editor.getByRole('button', { name: 'Save mix' })).toBeInViewport();
    await page.setViewportSize(viewport);
  }
  await editor.getByRole('button', { name: 'Save mix' }).click();
  const recipe = rack.getByRole('button', { name: 'Edit mix in slot 3' });
  await expect(recipe).toBeVisible();
  await expect(mixes).toHaveText('Mixes (1)');
  await expect(recipe).toHaveCSS('height', materialSlotHeight);
  const mixNumber = recipe.locator('.filament-slot-number');
  await expect(mixNumber).toHaveCSS('width', materialNumberWidth);
  await expect(mixNumber).toHaveCSS('background-image', /^linear-gradient/);
  await recipe.click({ button: 'right' });
  await verifyMergeChoices(page, 3, 1, /^1 - (?!Mix$).+/);
  await rack.getByTestId('filament-rack-toggle').click();
  await rack.getByTestId('filament-rack-toggle').click();
  await expect(recipe).toBeVisible();
  await recipe.click();
  await expect(editor.getByRole('checkbox', { name: 'Per-part gradient' })).toBeChecked();
  await expect(editor.getByLabel('First filament %')).toHaveCount(3);
  await editor.getByRole('combobox', { name: 'Component 1', exact: true }).click();
  await expect(page.getByRole('option')).toHaveCount(2);
  await page.keyboard.press('Escape');
  await editor.getByRole('button', { name: 'Cancel' }).click();
  await material.click();
  await rack.getByTestId('filament-add').click();
  await expect(rack.getByTestId('filament-slot-3')).toBeVisible();
  await mixes.click();
  await expect(rack.getByRole('button', { name: 'Edit mix in slot 4' })).toBeVisible();
  await material.click();
  await rack.getByTestId('filament-slot-2').click({ button: 'right' });
  await verifyMergeChoices(page, 2, 4, '4 - Mix');
  await rack.getByTestId('filament-slot-2').click({ button: 'right' });
  await page.getByTestId('filament-delete-2').click();
  const confirm = page.getByTestId('filament-impact-confirm');
  if (await confirm.isVisible()) await confirm.click();
  await expect(rack.getByTestId('filament-slot-3')).toHaveCount(0);
  await mixes.click();
  const damaged = rack.getByRole('button', { name: 'Edit mix in slot 3' });
  await expect(damaged).toContainText('missing filament', { ignoreCase: true });
  await expect(damaged).toHaveAccessibleDescription(/Missing filament/);
  await damaged.click();
  const secondComponent = editor.getByRole('combobox', { name: 'Component 2', exact: true });
  const selectedComponent = secondComponent.locator('[data-slot="select-value"]');
  await expect(selectedComponent).toHaveText('Missing filament');
  await secondComponent.click();
  const replacement = page.getByRole('option', { name: /^2 - / });
  await expect(replacement.locator('span[aria-hidden="true"]')).toHaveCSS('width', '14px');
  await replacement.click();
  await expect(selectedComponent).toHaveText(/^2 - /);
  await expect(selectedComponent.locator('span[aria-hidden="true"]')).toHaveCSS('width', '14px');
  await editor.getByRole('button', { name: 'Save mix' }).click();
  await expect(damaged).not.toContainText('missing filament', { ignoreCase: true });
  await material.click();
  await rack.getByTestId('filament-add').click();
  await expect(rack.getByTestId('filament-slot-3')).toBeVisible();
  await mixes.click();
  await rack.getByRole('button', { name: 'Delete all' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete all' }).click();
  await expect(rack.getByRole('button', { name: 'Edit mix in slot 4' })).toHaveCount(0);
  await expect(mixes).toHaveText('Mixes (0)');
  await expect(rack.getByTestId('filament-rejected')).toHaveCount(0);
  await rack.getByRole('button', { name: 'Create', exact: true }).click();
  await componentCount.click();
  await page.getByRole('option', { name: 'Three', exact: true }).click();
  await editor.getByLabel('Percentage 2').fill('35');
  await editor.getByLabel('Percentage 2').blur();
  await expect(editor.getByLabel('Percentage 2')).toHaveValue('35');
  await editor.getByRole('button', { name: 'Save mix' }).click();
  await expect(rack.getByRole('button', { name: 'Edit mix in slot 4' })).toContainText('35%');
  await material.click();
  await rack.getByTestId('filament-slot-2').click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Decompose Color' }).click();
  await expect(editor.getByRole('heading')).toContainText('Decompose Color');
  await editor.getByRole('combobox', { name: 'Palette', exact: true }).click();
  await page.getByRole('option', { name: 'Project materials' }).click();
  await editor.getByRole('button', { name: 'Create mix', exact: true }).click();
  await expect(rack.getByRole('button', { name: 'Edit mix in slot 5' })).toBeVisible();
  await expect(mixes).toHaveText('Mixes (2)');
  await addPrimitive(page, 'cube');
  await page.getByTestId('config-mode-scoped').click();
  const assignment = page.locator('[data-testid^="filament-cell-object-"]').first();
  await assignment.click();
  await expect(page.getByRole('option', { name: '5 - Mix', exact: true })).toBeVisible();
  await page.getByRole('option', { name: '4 - Mix', exact: true }).click();
  await expect(assignment).toHaveText('4');
  const tower = await page.evaluate(() => (window as Window & {
    __orcaE2e?: { primeTowerStates?: () => unknown }
  }).__orcaE2e?.primeTowerStates?.());
  await page.getByTestId('btn-slice').click();
  const status = page.getByTestId('slicer-status');
  await expect(status).toHaveText(/^(Sliced|Error)$/, { timeout: 120000 });
  await expect(status, `Mixed slice with tower ${JSON.stringify(tower)}`).toHaveText('Sliced');
  await page.getByTestId('preview-color-scheme').click();
  await page.getByTestId('preview-color-scheme-filament').click();
  for (const tool of [0, 1, 2]) await expect(page.getByTestId(`preview-scheme-visibility-filament-${tool}`)).toBeVisible();
  await expect(page.getByTestId('preview-scheme-visibility-filament-3')).toHaveCount(0);
}
